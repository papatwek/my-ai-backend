const express = require('express');
const { createClient } = require('@supabase/supabase-js');

const app = express();
app.use(express.json());

const supabase = createClient(
  process.env.SUPABASE_URL,
  process.env.SUPABASE_SERVICE_ROLE_KEY
);

const GEMINI_API_KEY = process.env.GEMINI_API_KEY;

app.post('/generate-reply', async (req, res) => {
  // Capture the session ID
  const activeSessionId = req.body.sessionId || req.body.session_id;
  // Extract the specific prompt and JSON format requested by your frontend
  const { messages, schema } = req.body;

  if (!activeSessionId) {
    console.error("Missing session ID!");
    return res.status(400).json({ error: 'Missing session ID in request' });
  }

  try {
    // 1. Separate system instructions from user/assistant chat history
    const systemInstructionText = (messages || [])
      .filter(m => m.role === 'system')
      .map(m => m.content || m.text)
      .join('\n\n');

    const contents = (messages || [])
      .filter(m => m.role !== 'system')
      .map(m => ({
        role: m.role === 'assistant' ? 'model' : 'user',
        parts: [{ text: m.content || m.text || '' }]
      }));

    if (contents.length === 0) {
      contents.push({ role: 'user', parts: [{ text: 'Please begin the scenario.' }] });
    }

    // 2. Prepare Gemini configuration to enforce the JSON schema
    const generationConfig = {
      temperature: 0.7,
    };

    if (schema) {
      generationConfig.responseMimeType = 'application/json';
      generationConfig.responseSchema = schema;
    }

    const requestBody = {
      contents: contents,
      generationConfig: generationConfig
    };

    if (systemInstructionText) {
      requestBody.system_instruction = {
        parts: [{ text: systemInstructionText }]
      };
    }

    // 3. Call the Gemini API directly
    const geminiResponse = await fetch(
      `https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent?key=${GEMINI_API_KEY}`,
      {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(requestBody)
      }
    );

    const geminiData = await geminiResponse.json();

    if (!geminiResponse.ok) {
       console.error("Gemini API Error:", JSON.stringify(geminiData));
       return res.status(500).json({ error: 'Failed at Gemini API' });
    }

    // 4. Extract the exact JSON response generated by Gemini
    const aiResponseText = geminiData?.candidates?.[0]?.content?.parts?.[0]?.text;

    if (!aiResponseText) {
      console.error("Empty Gemini response:", JSON.stringify(geminiData));
      return res.status(500).json({ error: 'No response from Gemini' });
    }

    // 5. Save the AI's response to Supabase so it shows up in history
    const { error: insertError } = await supabase
      .from('messages')
      .insert([{
        session_id: activeSessionId,
        role: 'assistant',
        content: aiResponseText
      }]);

    if (insertError) {
        console.error("Supabase Save Error:", insertError);
    }

    // 6. Return the perfectly formatted JSON string to Vercel/Frontend
    res.status(200).json({ content: aiResponseText });

  } catch (error) {
    console.error("Server error:", error);
    res.status(500).json({ error: 'Failed to generate AI response' });
  }
});

app.listen(8080, () => console.log('AI Orchestration server running on port 8080'));
